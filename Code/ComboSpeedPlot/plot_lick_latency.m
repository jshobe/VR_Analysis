function fig = plot_lick_latency( ...
    latencyInput, cfg, mouseName, sessionDate, comparisonBlocks)
% PLOT_LICK_LATENCY
% Compares reward-to-first-lick timing across one or more sessions.
%
% Each mouse receives a two-row block:
%   upper row  = one chronological raster per selected date
%   lower row  = one shared rolling-median comparison axis for that mouse
%
% Raster markers:
%   red dot   = reward delivery at time zero
%   white dot = first post-reward lick
%   gray line = reward-to-lick interval

latencyTables = normalize_latency_tables(latencyInput);
nSessions = numel(latencyTables);

mouseNames = normalize_session_labels( ...
    mouseName, ...
    nSessions, ...
    'UnknownMouse');

sessionDates = normalize_session_labels( ...
    sessionDate, ...
    nSessions, ...
    'UnknownDate');

requiredVariables = { ...
    'Lap', ...
    'RewardCount', ...
    'LickLatency_s', ...
    'IsRewardedLap', ...
    'IsOmissionLap', ...
    'HasMultipleRewards', ...
    'HasFirstLick'};

maxLap = 0;
for s = 1:nSessions
    T = latencyTables{s};

    for k = 1:numel(requiredVariables)
        if ~ismember(requiredVariables{k}, T.Properties.VariableNames)
            error( ...
                'Session %d latency table is missing variable %s.', ...
                s, ...
                requiredVariables{k});
        end
    end

    if isempty(T)
        error('Session %d latency table is empty.', s);
    end

    maxLap = max(maxLap, max(T.Lap));
end

if ~isfield(cfg, 'maxLickLatency_s') || ...
        ~isscalar(cfg.maxLickLatency_s) || ...
        ~isfinite(cfg.maxLickLatency_s) || ...
        cfg.maxLickLatency_s <= 0
    error('A finite positive cfg.maxLickLatency_s is required for plotting.');
end

if ~isfield(cfg, 'latencyRollingWindow_laps')
    cfg.latencyRollingWindow_laps = 10;
end

rollingWindow = max(1, round(cfg.latencyRollingWindow_laps));
displayMax_s = calculate_shared_display_max(latencyTables, cfg);

rollingLatencyBySession = cell(nSessions, 1);
for s = 1:nSessions
    rollingLatencyBySession{s} = movmedian( ...
        latencyTables{s}.LickLatency_s, ...
        rollingWindow, ...
        'omitnan');
end

fontSize = 20;
isSingleMouseSelection = numel(unique(mouseNames)) == 1;

if nargin >= 5 && ...
        ~isempty(comparisonBlocks) && ...
        isSingleMouseSelection
    pairedFontSize = fontSize / 1.5;
    fig = plot_comparison_blocks( ...
        latencyTables, ...
        mouseNames, ...
        sessionDates, ...
        comparisonBlocks, ...
        rollingLatencyBySession, ...
        displayMax_s, ...
        cfg, ...
        maxLap, ...
        rollingWindow, ...
        pairedFontSize);
    return
end

mouseOrder = sort(unique(mouseNames));
dateOrder = sort(unique(sessionDates));

nMice = numel(mouseOrder);
nDates = numel(dateOrder);
dateColors = lines(nDates);

validate_mouse_date_pairs( ...
    mouseNames, ...
    sessionDates, ...
    mouseOrder, ...
    dateOrder);

figWidth = max(1800, 650 * nDates);
figHeight = max(1100, 650 * nMice);

fig = figure( ...
    'Color', 'w', ...
    'Name', 'Stacked lick latency by mouse', ...
    'Units', 'pixels', ...
    'Position', [50 50 figWidth figHeight]);

tl = tiledlayout(fig, 2 * nMice, nDates, ...
    'TileSpacing', 'loose', ...
    'Padding', 'loose');
tl.Units = 'normalized';
tl.OuterPosition = [0.04 0.08 0.92 0.86];

for m = 1:nMice
    mouseLabel = mouseOrder{m};
    rasterRow = 2 * m - 1;
    trendRow = 2 * m;

    mouseSessionIdx = find(strcmp(mouseNames, mouseLabel));
    mouseTrendDisplayMax_s = calculate_trend_display_max( ...
        rollingLatencyBySession(mouseSessionIdx), ...
        cfg);
    availableDateColumns = find(arrayfun(@(d) any( ...
        strcmp(mouseNames, mouseLabel) & ...
        strcmp(sessionDates, dateOrder{d})), ...
        1:nDates));
    firstAvailableDateColumn = availableDateColumns(1);
    lastAvailableDateColumn = availableDateColumns(end);

    %% Raster row for this mouse
    for d = 1:nDates
        rasterTile = (rasterRow - 1) * nDates + d;
        axRaster = nexttile(tl, rasterTile);

        sessionIdx = find( ...
            strcmp(mouseNames, mouseLabel) & ...
            strcmp(sessionDates, dateOrder{d}));

        if isempty(sessionIdx)
            axis(axRaster, 'off');
            continue
        end

        plot_session_raster( ...
            axRaster, ...
            latencyTables{sessionIdx}, ...
            mouseNames{sessionIdx}, ...
            sessionDates{sessionIdx}, ...
            dateColors(d, :), ...
            displayMax_s, ...
            maxLap, ...
            d == firstAvailableDateColumn, ...
            m == 1 && d == lastAvailableDateColumn, ...
            fontSize, ...
            false);
    end

    %% Rolling-median comparison row for this mouse
    trendTile = (trendRow - 1) * nDates + 1;
    axTrend = nexttile(tl, trendTile, [1 nDates]);
    hold(axTrend, 'on');

    curveHandles = gobjects(numel(mouseSessionIdx), 1);
    curveLabels = cell(numel(mouseSessionIdx), 1);

    curveCount = 0;
    for d = 1:nDates
        sessionIdx = find( ...
            strcmp(mouseNames, mouseLabel) & ...
            strcmp(sessionDates, dateOrder{d}));

        if isempty(sessionIdx)
            continue
        end

        curveCount = curveCount + 1;
        T = latencyTables{sessionIdx};

        curveHandles(curveCount) = plot(axTrend, ...
            T.Lap, ...
            rollingLatencyBySession{sessionIdx}, ...
            '-', ...
            'Color', dateColors(d, :), ...
            'LineWidth', 2);

        curveLabels{curveCount} = dateOrder{d};
    end

    xlim(axTrend, [0.5 maxLap + 0.5]);
    ylim(axTrend, [0 mouseTrendDisplayMax_s]);

    xlabel(axTrend, 'Lap', 'FontSize', fontSize);
    ylabel(axTrend, 'First-lick latency (s)', 'FontSize', fontSize);
    title(axTrend, sprintf( ...
        '%s: %d-lap rolling median by session', ...
        mouseLabel, ...
        rollingWindow), ...
        'Interpreter', 'none', ...
        'FontSize', fontSize);

    set(axTrend, 'FontSize', fontSize);
    grid(axTrend, 'on');
    box(axTrend, 'on');

    legend(axTrend, ...
        curveHandles(1:curveCount), ...
        curveLabels(1:curveCount), ...
        'Location', 'northeast', ...
        'Interpreter', 'none', ...
        'FontSize', fontSize);
end

end


function fig = plot_comparison_blocks( ...
    latencyTables, mouseNames, sessionDates, comparisonBlocks, ...
    rollingLatencyBySession, displayMax_s, cfg, maxLap, ...
    rollingWindow, fontSize)

nSessions = numel(latencyTables);
comparisonBlocks = comparisonBlocks(:);

if numel(comparisonBlocks) ~= nSessions || ...
        ~isnumeric(comparisonBlocks) || ...
        any(~isfinite(comparisonBlocks))
    error([ ...
        'comparisonBlocks must contain one finite numeric block ID ' ...
        'per selected session.']);
end

blockOrder = unique(comparisonBlocks, 'stable');
nBlocks = numel(blockOrder);
nSessionsPerBlock = 2;

for b = 1:nBlocks
    if sum(comparisonBlocks == blockOrder(b)) ~= nSessionsPerBlock
        error('Each comparison block must contain exactly two sessions.');
    end
end

dateOrder = sort(unique(sessionDates));
dateColors = lines(numel(dateOrder));
nBootstrap = 10000;
nPermutations = 10000;
resamplingStream = RandStream('mt19937ar', 'Seed', 240517);

fig = figure( ...
    'Color', 'w', ...
    'Name', 'Paired lick latency comparisons', ...
    'Units', 'pixels', ...
    'Position', [50 50 1800 900]);

outerLeft = 0.08;
outerRight = 0.035;
outerBottom = 0.14;
outerTop = 0.10;
blockGap = 0.16;
statsPanelWidth = 0.22;
statsPanelGap = 0.09;
rasterGap = 0.035;

availableHeight = ...
    1 - outerBottom - outerTop - (nBlocks - 1) * blockGap;
blockHeight = availableHeight / nBlocks;
trendHeight = 0.37 * blockHeight;
withinBlockGap = 0.27 * blockHeight;
rasterHeight = blockHeight - trendHeight - withinBlockGap;

contentWidth = ...
    1 - outerLeft - outerRight - statsPanelGap - statsPanelWidth;
rasterWidth = (contentWidth - rasterGap) / nSessionsPerBlock;
statsPanelLeft = outerLeft + contentWidth + statsPanelGap;

for b = 1:nBlocks
    blockSessionIdx = find(comparisonBlocks == blockOrder(b));
    [~, dateSortIdx] = sort(sessionDates(blockSessionIdx));
    blockSessionIdx = blockSessionIdx(dateSortIdx);

    blockBottom = outerBottom + ...
        (nBlocks - b) * (blockHeight + blockGap);
    rasterBottom = blockBottom + trendHeight + withinBlockGap;

    blockColors = zeros(nSessionsPerBlock, 3);
    blockStatistics = repmat(struct( ...
        'Median_s', nan, ...
        'CILower_s', nan, ...
        'CIUpper_s', nan, ...
        'N', 0), ...
        nSessionsPerBlock, ...
        1);

    for c = 1:nSessionsPerBlock
        sessionIdx = blockSessionIdx(c);
        dateColorIdx = find( ...
            strcmp(dateOrder, sessionDates{sessionIdx}), ...
            1);
        blockColors(c, :) = dateColors(dateColorIdx, :);

        axRaster = axes( ...
            'Parent', fig, ...
            'Position', [ ...
                outerLeft + (c - 1) * (rasterWidth + rasterGap), ...
                rasterBottom, ...
                rasterWidth, ...
                rasterHeight]);

        plot_session_raster( ...
            axRaster, ...
            latencyTables{sessionIdx}, ...
            mouseNames{sessionIdx}, ...
            sessionDates{sessionIdx}, ...
            blockColors(c, :), ...
            displayMax_s, ...
            maxLap, ...
            c == 1, ...
            b == 1 && c == nSessionsPerBlock, ...
            fontSize, ...
            true);

        validLatencies = select_valid_trial_latencies( ...
            latencyTables{sessionIdx}, ...
            cfg.maxLickLatency_s);
        blockStatistics(c) = bootstrap_median_statistics( ...
            validLatencies, ...
            nBootstrap, ...
            resamplingStream);
    end

    sessionLatencies = cell(nSessionsPerBlock, 1);
    for c = 1:nSessionsPerBlock
        sessionIdx = blockSessionIdx(c);
        sessionLatencies{c} = select_valid_trial_latencies( ...
            latencyTables{sessionIdx}, ...
            cfg.maxLickLatency_s);
    end

    permutationP = permutation_test_median_difference( ...
        sessionLatencies{1}, ...
        sessionLatencies{2}, ...
        nPermutations, ...
        resamplingStream);

    interactionSeed = deterministic_interaction_seed( ...
        mouseNames{blockSessionIdx(1)}, ...
        sessionDates{blockSessionIdx(1)}, ...
        sessionDates{blockSessionIdx(2)});
    interactionStatistics = session_by_lap_block_interaction( ...
        latencyTables{blockSessionIdx(1)}, ...
        latencyTables{blockSessionIdx(2)}, ...
        cfg.maxLickLatency_s, ...
        rollingWindow, ...
        nPermutations, ...
        interactionSeed);

    trendDisplayMax_s = calculate_trend_display_max( ...
        rollingLatencyBySession(blockSessionIdx), ...
        cfg);

    [barDisplayMax_s, bracketBase_s, bracketTop_s, pTextY_s] = ...
        calculate_bar_display_limits([blockStatistics.CIUpper_s]);

    axTrend = axes( ...
        'Parent', fig, ...
        'Position', [ ...
            outerLeft, ...
            blockBottom, ...
            contentWidth, ...
            trendHeight]);
    hold(axTrend, 'on');

    curveHandles = gobjects(nSessionsPerBlock, 1);
    curveLabels = cell(nSessionsPerBlock, 1);

    for c = 1:nSessionsPerBlock
        sessionIdx = blockSessionIdx(c);
        T = latencyTables{sessionIdx};

        curveHandles(c) = plot(axTrend, ...
            T.Lap, ...
            rollingLatencyBySession{sessionIdx}, ...
            '-', ...
            'Color', blockColors(c, :), ...
            'LineWidth', 2);

        curveLabels{c} = sessionDates{sessionIdx};
    end

    xlim(axTrend, [0.5 maxLap + 0.5]);
    ylim(axTrend, [0 trendDisplayMax_s]);

    xlabel(axTrend, 'Lap', 'FontSize', fontSize);
    ylabel(axTrend, 'First-lick latency (s)', 'FontSize', fontSize);
    shortDate1 = regexprep( ...
        sessionDates{blockSessionIdx(1)}, ...
        '^\d{4}-', ...
        '');
    shortDate2 = regexprep( ...
        sessionDates{blockSessionIdx(2)}, ...
        '^\d{4}-', ...
        '');

    trendTitle = title(axTrend, sprintf( ...
        '%s %s vs %s | %d-lap rolling median', ...
        mouseNames{blockSessionIdx(1)}, ...
        shortDate1, ...
        shortDate2, ...
        rollingWindow), ...
        'Interpreter', 'none', ...
        'FontSize', fontSize);
    set(trendTitle, ...
        'Units', 'normalized', ...
        'Position', [0.5 0.94 0], ...
        'VerticalAlignment', 'top', ...
        'BackgroundColor', 'w', ...
        'Margin', 4);

    text(axTrend, ...
        0.02, ...
        0.96, ...
        { ...
            sprintf('Median session %c block interaction', char(215)), ...
            sprintf( ...
                'Trial-level permutation: p = %.5f', ...
                interactionStatistics.PValue)}, ...
        'Units', 'normalized', ...
        'HorizontalAlignment', 'left', ...
        'VerticalAlignment', 'top', ...
        'Interpreter', 'none', ...
        'Clipping', 'on', ...
        'BackgroundColor', 'w', ...
        'Margin', 4, ...
        'FontSize', fontSize);

    set(axTrend, ...
        'Color', 'white', ...
        'FontSize', fontSize);
    grid(axTrend, 'on');
    box(axTrend, 'on');

    legend(axTrend, ...
        curveHandles, ...
        curveLabels, ...
        'Location', 'southeast', ...
        'Interpreter', 'none', ...
        'FontSize', fontSize);

    axStatistics = axes( ...
        'Parent', fig, ...
        'Position', [ ...
            statsPanelLeft, ...
            blockBottom, ...
            statsPanelWidth, ...
            blockHeight]);
    hold(axStatistics, 'on');

    medians_s = [blockStatistics.Median_s];
    ciLower_s = [blockStatistics.CILower_s];
    ciUpper_s = [blockStatistics.CIUpper_s];

    for c = 1:nSessionsPerBlock
        bar( ...
            axStatistics, ...
            c, ...
            medians_s(c), ...
            0.62, ...
            'FaceColor', blockColors(c, :), ...
            'EdgeColor', 'none');

        errorbar( ...
            axStatistics, ...
            c, ...
            medians_s(c), ...
            medians_s(c) - ciLower_s(c), ...
            ciUpper_s(c) - medians_s(c), ...
            'LineStyle', 'none', ...
            'Marker', 'none', ...
            'Color', blockColors(c, :), ...
            'LineWidth', 1.8, ...
            'CapSize', 8);
    end

    plot(axStatistics, ...
        [1 1 2 2], ...
        [bracketBase_s bracketTop_s bracketTop_s bracketBase_s], ...
        '-', ...
        'Color', [0.1 0.1 0.1], ...
        'LineWidth', 1.2);

    text(axStatistics, ...
        1.5, ...
        pTextY_s, ...
        sprintf('p = %.5f', permutationP), ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'bottom', ...
        'Clipping', 'on', ...
        'FontSize', fontSize, ...
        'FontWeight', 'bold');

    xlim(axStatistics, [0.35 2.65]);
    ylim(axStatistics, [0 barDisplayMax_s]);
    xticks(axStatistics, 1:nSessionsPerBlock);
    xticklabels(axStatistics, sessionDates(blockSessionIdx));
    xtickangle(axStatistics, 35);
    ylabel(axStatistics, 'Median latency (s)', 'FontSize', fontSize);
    title(axStatistics, { ...
        'Session median', ...
        'Trial-level permutation'}, ...
        'FontSize', fontSize, ...
        'FontWeight', 'bold');
    set(axStatistics, 'FontSize', fontSize);
    grid(axStatistics, 'on');
    box(axStatistics, 'on');

    fprintf([ ...
        'Trial-level within-mouse comparison: %s %s ' ...
        'median %.6f s (95%% bootstrap CI %.6f to %.6f, n=%d) vs ' ...
        '%s median %.6f s (95%% bootstrap CI %.6f to %.6f, n=%d) | ' ...
        'two-sided permutation p=%.8f\n'], ...
        mouseNames{blockSessionIdx(1)}, ...
        sessionDates{blockSessionIdx(1)}, ...
        blockStatistics(1).Median_s, ...
        blockStatistics(1).CILower_s, ...
        blockStatistics(1).CIUpper_s, ...
        blockStatistics(1).N, ...
        sessionDates{blockSessionIdx(2)}, ...
        blockStatistics(2).Median_s, ...
        blockStatistics(2).CILower_s, ...
        blockStatistics(2).CIUpper_s, ...
        blockStatistics(2).N, ...
        permutationP);

    fprintf([ ...
        '%s %s vs %s median/LAD session x %d-lap block interaction: ' ...
        'T=%.12g | exceedances=%d/%d | corrected p=%.8f | seed=%d | ' ...
        'reduced nonunique=%d (session-coefficient interval %.12g s) | ' ...
        'full nonunique cells=%d | convergence failures=%d\n'], ...
        mouseNames{blockSessionIdx(1)}, ...
        sessionDates{blockSessionIdx(1)}, ...
        sessionDates{blockSessionIdx(2)}, ...
        rollingWindow, ...
        interactionStatistics.ObservedStatistic, ...
        interactionStatistics.ExceedanceCount, ...
        interactionStatistics.NPermutations, ...
        interactionStatistics.PValue, ...
        interactionStatistics.Seed, ...
        interactionStatistics.ReducedNonunique, ...
        interactionStatistics.ReducedSessionCoefficientWidth_s, ...
        interactionStatistics.FullNonuniqueCellCount, ...
        interactionStatistics.ConvergenceFailures);
end

end


function [latencies_s, laps] = select_valid_trial_latencies( ...
    T, maxLatency_s)

validTrial = ...
    T.RewardCount == 1 & ...
    T.IsRewardedLap & ...
    ~T.IsOmissionLap & ...
    ~T.HasMultipleRewards & ...
    T.HasFirstLick & ...
    isfinite(T.LickLatency_s) & ...
    T.LickLatency_s >= 0 & ...
    T.LickLatency_s <= maxLatency_s;

latencies_s = T.LickLatency_s(validTrial);
laps = T.Lap(validTrial);

if isempty(latencies_s)
    error('A paired session has no valid trial-level lick latencies.');
end

end


function statistics = bootstrap_median_statistics( ...
    values, nBootstrap, resamplingStream)

values = values(:);
nValues = numel(values);
bootstrapIndices = randi( ...
    resamplingStream, ...
    nValues, ...
    nValues, ...
    nBootstrap);
bootstrapMedians = median(values(bootstrapIndices), 1);
confidenceInterval = prctile(bootstrapMedians, [2.5 97.5]);

statistics = struct( ...
    'Median_s', median(values), ...
    'CILower_s', confidenceInterval(1), ...
    'CIUpper_s', confidenceInterval(2), ...
    'N', nValues);

end


function pValue = permutation_test_median_difference( ...
    values1, values2, nPermutations, resamplingStream)

values1 = values1(:);
values2 = values2(:);
nValues1 = numel(values1);
pooledValues = [values1; values2];
nTotal = numel(pooledValues);
observedDifference = median(values1) - median(values2);
extremeCount = 0;

for permutation = 1:nPermutations
    permutedIndices = randperm(resamplingStream, nTotal);
    permutedDifference = ...
        median(pooledValues(permutedIndices(1:nValues1))) - ...
        median(pooledValues(permutedIndices(nValues1 + 1:end)));

    if abs(permutedDifference) >= abs(observedDifference)
        extremeCount = extremeCount + 1;
    end
end

% The plus-one correction yields a valid finite-resampling p-value and
% prevents reporting zero when no sampled permutation is more extreme.
pValue = (extremeCount + 1) / (nPermutations + 1);

end


function statistics = session_by_lap_block_interaction( ...
    table1, table2, maxLatency_s, lapBlockSize, ...
    nPermutations, randomSeed)

[latency1, lap1] = select_valid_trial_latencies( ...
    table1, ...
    maxLatency_s);
[latency2, lap2] = select_valid_trial_latencies( ...
    table2, ...
    maxLatency_s);

block1 = ceil(lap1 / lapBlockSize);
block2 = ceil(lap2 / lapBlockSize);
requiredBlocks = (1:10)';

keep1 = ismember(block1, requiredBlocks);
keep2 = ismember(block2, requiredBlocks);

latency = [latency1(keep1); latency2(keep2)];
sessionGroup = [ ...
    zeros(sum(keep1), 1); ...
    ones(sum(keep2), 1)];
lapBlock = [block1(keep1); block2(keep2)];

for block = requiredBlocks'
    for session = 0:1
        if ~any(lapBlock == block & sessionGroup == session)
            error([ ...
                'Median/LAD interaction requires valid observations in ' ...
                'every session-by-10-lap-block cell.']);
        end
    end
end

previousRandomState = rng;
randomStateCleanup = onCleanup(@() rng(previousRandomState));
resamplingStream = RandStream('mt19937ar', 'Seed', randomSeed);

[reducedAbsoluteError, reducedFitted, reducedExitFlag] = ...
    fit_additive_lad( ...
        latency, ...
        sessionGroup, ...
        lapBlock, ...
        requiredBlocks, ...
        maxLatency_s);
fullAbsoluteError = fit_interaction_lad( ...
    latency, ...
    sessionGroup, ...
    lapBlock, ...
    requiredBlocks);
observedStatistic = reducedAbsoluteError - fullAbsoluteError;
reducedResidual = latency - reducedFitted;
exceedanceCount = 0;
convergenceFailures = double(reducedExitFlag <= 0);

for permutation = 1:nPermutations
    permutedResidual = reducedResidual;

    for block = requiredBlocks'
        blockRows = find(lapBlock == block);
        blockOrder = randperm(resamplingStream, numel(blockRows));
        permutedResidual(blockRows) = ...
            reducedResidual(blockRows(blockOrder));
    end

    permutedLatency = reducedFitted + permutedResidual;
    [permutedReducedError, ~, permutedExitFlag] = ...
        fit_additive_lad( ...
            permutedLatency, ...
            sessionGroup, ...
            lapBlock, ...
            requiredBlocks, ...
            maxLatency_s);
    permutedFullError = fit_interaction_lad( ...
        permutedLatency, ...
        sessionGroup, ...
        lapBlock, ...
        requiredBlocks);
    permutedStatistic = ...
        permutedReducedError - permutedFullError;

    if permutedExitFlag <= 0
        convergenceFailures = convergenceFailures + 1;
    end

    if permutedStatistic >= observedStatistic
        exceedanceCount = exceedanceCount + 1;
    end
end

[reducedWidth_s, reducedDiagnosticFailure] = ...
    reduced_lad_session_coefficient_width( ...
        latency, ...
        sessionGroup, ...
        lapBlock, ...
        requiredBlocks);
fullNonuniqueCellCount = count_nonunique_cell_medians( ...
    latency, ...
    sessionGroup, ...
    lapBlock, ...
    requiredBlocks);

convergenceFailures = ...
    convergenceFailures + double(reducedDiagnosticFailure);

statistics = struct( ...
    'ReducedAbsoluteError', reducedAbsoluteError, ...
    'FullAbsoluteError', fullAbsoluteError, ...
    'ObservedStatistic', observedStatistic, ...
    'ExceedanceCount', exceedanceCount, ...
    'NPermutations', nPermutations, ...
    'PValue', (exceedanceCount + 1) / (nPermutations + 1), ...
    'Seed', randomSeed, ...
    'ReducedSessionCoefficientWidth_s', reducedWidth_s, ...
    'ReducedNonunique', reducedWidth_s > 1e-6, ...
    'FullNonuniqueCellCount', fullNonuniqueCellCount, ...
    'ConvergenceFailures', convergenceFailures);

clear randomStateCleanup
rng(previousRandomState);

end


function [absoluteError, fittedValues, exitFlag] = fit_additive_lad( ...
    latency, sessionGroup, lapBlock, blockIDs, maxLatency_s)

options = optimset( ...
    'Display', ...
    'off', ...
    'TolX', ...
    1e-10);

[sessionCoefficient, absoluteError, exitFlag] = fminbnd( ...
    @(candidate) additive_lad_absolute_error( ...
        candidate, ...
        latency, ...
        sessionGroup, ...
        lapBlock, ...
        blockIDs), ...
    -maxLatency_s, ...
    maxLatency_s, ...
    options);

fittedValues = nan(size(latency));

for block = blockIDs'
    blockRows = lapBlock == block;
    blockIntercept = median( ...
        latency(blockRows) - ...
        sessionCoefficient * sessionGroup(blockRows));
    fittedValues(blockRows) = ...
        blockIntercept + ...
        sessionCoefficient * sessionGroup(blockRows);
end

end


function absoluteError = additive_lad_absolute_error( ...
    sessionCoefficient, latency, sessionGroup, lapBlock, blockIDs)

absoluteError = 0;

for block = blockIDs'
    blockRows = lapBlock == block;
    adjustedLatency = ...
        latency(blockRows) - ...
        sessionCoefficient * sessionGroup(blockRows);
    blockIntercept = median(adjustedLatency);
    absoluteError = absoluteError + ...
        sum(abs(adjustedLatency - blockIntercept));
end

end


function absoluteError = fit_interaction_lad( ...
    latency, sessionGroup, lapBlock, blockIDs)

absoluteError = 0;

for block = blockIDs'
    for session = 0:1
        cellValues = latency( ...
            lapBlock == block & ...
            sessionGroup == session);
        absoluteError = absoluteError + ...
            sum(abs(cellValues - median(cellValues)));
    end
end

end


function [sessionWidth_s, diagnosticFailure] = ...
    reduced_lad_session_coefficient_width( ...
        latency, sessionGroup, lapBlock, blockIDs)

nValues = numel(latency);
nBlocks = numel(blockIDs);
blockDesign = zeros(nValues, nBlocks);

for column = 1:nBlocks
    blockDesign(:, column) = lapBlock == blockIDs(column);
end

design = [blockDesign sessionGroup];
nCoefficients = size(design, 2);
constraintMatrix = [ ...
    design -eye(nValues); ...
    -design -eye(nValues)];
constraintBound = [latency; -latency];
objective = [zeros(nCoefficients, 1); ones(nValues, 1)];
lowerBound = [-inf(nCoefficients, 1); zeros(nValues, 1)];
options = optimoptions( ...
    'linprog', ...
    'Display', ...
    'none', ...
    'Algorithm', ...
    'dual-simplex');

[~, optimum, optimumExitFlag] = linprog( ...
    objective, ...
    constraintMatrix, ...
    constraintBound, ...
    [], ...
    [], ...
    lowerBound, ...
    [], ...
    options);

if optimumExitFlag <= 0
    sessionWidth_s = nan;
    diagnosticFailure = true;
    return
end

optimalConstraint = [ ...
    zeros(1, nCoefficients) ones(1, nValues)];
boundedConstraintMatrix = [ ...
    constraintMatrix; ...
    optimalConstraint];
boundedConstraintBound = [ ...
    constraintBound; ...
    optimum + 1e-9];
sessionObjective = zeros(nCoefficients + nValues, 1);
sessionObjective(nCoefficients) = 1;

[minimumSolution, ~, minimumExitFlag] = linprog( ...
    sessionObjective, ...
    boundedConstraintMatrix, ...
    boundedConstraintBound, ...
    [], ...
    [], ...
    lowerBound, ...
    [], ...
    options);
[maximumSolution, ~, maximumExitFlag] = linprog( ...
    -sessionObjective, ...
    boundedConstraintMatrix, ...
    boundedConstraintBound, ...
    [], ...
    [], ...
    lowerBound, ...
    [], ...
    options);

diagnosticFailure = ...
    minimumExitFlag <= 0 || ...
    maximumExitFlag <= 0;

if diagnosticFailure
    sessionWidth_s = nan;
else
    sessionWidth_s = ...
        maximumSolution(nCoefficients) - ...
        minimumSolution(nCoefficients);
end

end


function count = count_nonunique_cell_medians( ...
    latency, sessionGroup, lapBlock, blockIDs)

count = 0;

for block = blockIDs'
    for session = 0:1
        cellValues = sort(latency( ...
            lapBlock == block & ...
            sessionGroup == session));
        nValues = numel(cellValues);

        if mod(nValues, 2) == 0 && ...
                cellValues(nValues / 2 + 1) - ...
                cellValues(nValues / 2) > 1e-12
            count = count + 1;
        end
    end
end

end


function randomSeed = deterministic_interaction_seed( ...
    mouseName, firstDate, secondDate)

key = [mouseName '|' firstDate '|' secondDate];
weights = 1:numel(key);
randomSeed = 250000 + mod( ...
    sum(double(key) .* weights), ...
    100000);

end


function [yMax_s, bracketBase_s, bracketTop_s, pTextY_s] = ...
    calculate_bar_display_limits(ciUpper_s)

