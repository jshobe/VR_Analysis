function validate_mouse_date_pairs( ...
    mouseNames, sessionDates, mouseOrder, dateOrder)

for m = 1:numel(mouseOrder)
    for d = 1:numel(dateOrder)
        pairCount = sum( ...
            strcmp(mouseNames, mouseOrder{m}) & ...
            strcmp(sessionDates, dateOrder{d}));

        if pairCount > 1
            error([ ...
                'Multiple files were selected for mouse %s on %s. ' ...
                'Select only one session per mouse and date.'], ...
                mouseOrder{m}, ...
                dateOrder{d});
        end
    end
end

end


function trendDisplayMax_s = calculate_trend_display_max( ...
    rollingLatencyBySession, cfg)

if isfield(cfg, 'latencyTrendDisplayMax_s') && ...
        ~isempty(cfg.latencyTrendDisplayMax_s)
    trendDisplayMax_s = cfg.latencyTrendDisplayMax_s;

    if ~isscalar(trendDisplayMax_s) || ...
            ~isfinite(trendDisplayMax_s) || ...
            trendDisplayMax_s <= 0
        error( ...
            'cfg.latencyTrendDisplayMax_s must be a positive finite scalar.');
    end

    return
end

if isfield(cfg, 'minimumLatencyTrendDisplayMax_s')
    minimumTrendMax_s = cfg.minimumLatencyTrendDisplayMax_s;
else
    minimumTrendMax_s = 0.5;
end

rollingValues = [];

for s = 1:numel(rollingLatencyBySession)
    values = rollingLatencyBySession{s};
    rollingValues = [ ...
        rollingValues; ...
        values(isfinite(values))]; %#ok<AGROW>
end

if isempty(rollingValues)
    trendDisplayMax_s = min( ...
        cfg.maxLickLatency_s, ...
        minimumTrendMax_s);
else
    paddedTrendMax_s = 1.15 * max(rollingValues);
    roundedTrendMax_s = ceil(10 * paddedTrendMax_s) / 10;

    trendDisplayMax_s = min( ...
        cfg.maxLickLatency_s, ...
        max(minimumTrendMax_s, roundedTrendMax_s));
end

end


function latencyTables = normalize_latency_tables(latencyInput)
if istable(latencyInput)
    latencyTables = {latencyInput};
elseif iscell(latencyInput) && ...
        ~isempty(latencyInput) && ...
        all(cellfun(@istable, latencyInput))
    latencyTables = latencyInput(:)';
else
    error('latencyInput must be a table or a nonempty cell array of tables.');
end
end


function labels = normalize_session_labels( ...
    labelInput, nSessions, fallbackLabel)

if nargin < 1 || isempty(labelInput)
    labels = repmat({fallbackLabel}, nSessions, 1);
elseif ischar(labelInput)
    labels = repmat({labelInput}, nSessions, 1);
elseif isstring(labelInput)
    labels = cellstr(labelInput(:));
elseif iscell(labelInput)
    labels = labelInput(:);
else
    error('Session labels must be text or a cell array of text.');
end

if numel(labels) ~= nSessions
    error('The number of session labels must match the number of tables.');
end

for s = 1:nSessions
    if isstring(labels{s}) && isscalar(labels{s})
        labels{s} = char(labels{s});
    end

    if ~ischar(labels{s})
        error('Every session label must be text.');
    end
end

end


function displayMax_s = calculate_shared_display_max( ...
    latencyTables, cfg)

if isfield(cfg, 'latencyDisplayMax_s') && ...
        ~isempty(cfg.latencyDisplayMax_s)
    displayMax_s = cfg.latencyDisplayMax_s;

    if ~isscalar(displayMax_s) || ...
            ~isfinite(displayMax_s) || ...
            displayMax_s <= 0
        error('cfg.latencyDisplayMax_s must be a positive finite scalar.');
    end

    return
end

if isfield(cfg, 'minimumLatencyDisplayMax_s')
    minimumDisplayMax_s = cfg.minimumLatencyDisplayMax_s;
else
    minimumDisplayMax_s = 0.5;
end

observedLatency = [];

for s = 1:numel(latencyTables)
    T = latencyTables{s};
    observedLatency = [ ...
        observedLatency; ...
        T.LickLatency_s(T.HasFirstLick)]; %#ok<AGROW>
end

if isempty(observedLatency)
    displayMax_s = min( ...
        cfg.maxLickLatency_s, ...
        minimumDisplayMax_s);
else
    paddedObservedMax_s = 1.15 * max(observedLatency);
    roundedObservedMax_s = ceil(10 * paddedObservedMax_s) / 10;

    displayMax_s = min( ...
        cfg.maxLickLatency_s, ...
        max(minimumDisplayMax_s, roundedObservedMax_s));
end

end


function plot_session_raster( ...
    ax, T, mouseName, sessionDate, titleColor, ...
    displayMax_s, maxLap, showYLabel, showLegend, fontSize, ...
    showTenLapTicks)

validReward = T.IsRewardedLap;
validLick = T.HasFirstLick;

hold(ax, 'on');
set(ax, ...
    'Color', [0 0 0], ...
    'YDir', 'reverse', ...
    'Layer', 'top');

lickRows = find(validLick);
for k = 1:numel(lickRows)
    row = lickRows(k);
    plot(ax, ...
        [0 T.LickLatency_s(row)], ...
        [T.Lap(row) T.Lap(row)], ...
        '-', ...
        'Color', [0.55 0.55 0.55], ...
        'LineWidth', 0.7);
end

scatter(ax, ...
    zeros(sum(validReward), 1), ...
    T.Lap(validReward), ...
    28, ...
    'o', ...
    'filled', ...
    'MarkerFaceColor', [1 0 0], ...
    'MarkerEdgeColor', [1 0 0]);

scatter(ax, ...
    T.LickLatency_s(validLick), ...
    T.Lap(validLick), ...
    20, ...
    'o', ...
    'filled', ...
    'MarkerFaceColor', [1 1 1], ...
    'MarkerEdgeColor', [1 1 1]);

xline(ax, 0, ':', ...
    'Color', [1 0.25 0.25], ...
    'LineWidth', 1);

xPadding = 0.03 * displayMax_s;
xlim(ax, [-xPadding displayMax_s]);
ylim(ax, [0.5 maxLap + 0.5]);

if showTenLapTicks
    yticks(ax, 10:10:maxLap);
end

xlabel(ax, 'Time from reward (s)', 'FontSize', fontSize);

if showYLabel
    ylabel(ax, 'Lap', 'FontSize', fontSize);
end

title(ax, { ...
    sprintf('%s  %s', mouseName, sessionDate), ...
    sprintf( ...
        '%d rewarded | %d omissions | %d first licks', ...
        sum(T.IsRewardedLap), ...
        sum(T.IsOmissionLap), ...
        sum(T.HasFirstLick))}, ...
    'Interpreter', 'none', ...
    'Color', titleColor, ...
    'FontSize', fontSize);

set(ax, 'FontSize', fontSize);

if showLegend
    hReward = scatter(ax, nan, nan, 28, ...
        'o', 'filled', ...
        'MarkerFaceColor', [1 0 0], ...
        'MarkerEdgeColor', [1 0 0]);
    hLick = scatter(ax, nan, nan, 20, ...
        'o', 'filled', ...
        'MarkerFaceColor', [1 1 1], ...
        'MarkerEdgeColor', [1 1 1]);

    legend(ax, ...
        [hReward hLick], ...
        {'Reward', 'First lick'}, ...
        'Location', 'southeast', ...
        'Color', [0.12 0.12 0.12], ...
        'TextColor', [1 1 1], ...
        'EdgeColor', [0.6 0.6 0.6], ...
        'FontSize', fontSize);
end

box(ax, 'on');

end
